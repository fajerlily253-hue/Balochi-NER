#tokenizera loading
from transformers import AutoTokenizer
model_name ="xlm-roberta-base"
tokenizer =AutoTokenizer.from_pretrained(model_name)
print("Tokenizer loaded successfully")

# seperating sentence and labels
sentences = []
labels = []
current_sentence = []
current_label = []

with open("path of your dataset ", "r", encoding="utf-8") as f:
    for line in f:
        line = line.strip()

        # empty line means the end of the sentence
        if line == "":
            if current_sentence:
                sentences.append(current_sentence)
                labels.append(current_label)
                current_sentence = []
                current_label = []
            continue

        # skip comments
        if line.startswith("#"):
            continue

        parts = line.split()
        if len(parts) >= 2:
            current_sentence.append(parts[0])
            current_label.append(parts[-1])

# print sentence and its label
print(sentences[0])
print(labels[0])

#unique labels
unique_labels = sorted(list(set(label for sentence in labels for label in sentence)))
print(unique_labels)

#creat data and mapping(label to id and id to label)
label2id ={label: i for i,label in
           enumerate(unique_labels)}
id2label = {i:label for label,i in label2id.items()}
print(label2id)

from datasets import Dataset
#creating hugging face dataset
dataset = Dataset.from_dict({
    "tokens": sentences,
    "ner_tags": labels
})
print(dataset)
#checking first example
print(dataset[0])

#splitting into trainig and testing sets
dataset = dataset.train_test_split(test_size=0.2,seed=42)

train_dataset =dataset["train"]
test_dataset = dataset["test"]

print("training samples:",len(train_dataset))
print("testing samples:",len(test_dataset))

# labels to id
def convert_labels(example):
    example["ner_tags"] = [
        label2id[label]
        for label in example["ner_tags"]
    ]
    return example

train_dataset = train_dataset.map(convert_labels)
test_dataset = test_dataset.map(convert_labels)

print(train_dataset[0])

def tokenize_and_align_labels(examples):
    tokenized_inputs = tokenizer(
        examples["tokens"],
        truncation=True,
        is_split_into_words=True
    )

    labels = []

    for i, label in enumerate(examples["ner_tags"]):
        word_ids = tokenized_inputs.word_ids(batch_index=i)
        previous_word_idx = None
        label_ids = []

        for word_idx in word_ids:
            if word_idx is None:
                label_ids.append(-100)
            elif word_idx != previous_word_idx:
                label_ids.append(label[word_idx])
            else:
                label_ids.append(-100)

            previous_word_idx = word_idx

        labels.append(label_ids)

    tokenized_inputs["labels"] = labels
    return tokenized_inputs

#apply tokenization and label alignment
tokenized_train = train_dataset.map(
    tokenize_and_align_labels,
    batched=True
)

tokenized_test = test_dataset.map(
    tokenize_and_align_labels,
    batched=True
)

#loading model
from transformers import AutoModelForTokenClassification
label_list = unique_labels

model = AutoModelForTokenClassification.from_pretrained(
    "xlm-roberta-base",
    num_labels=len(label_list),
    id2label=id2label,
    label2id=label2id
)

print("Model loaded successfully")

#create data collector
from transformers import DataCollatorForTokenClassification

data_collator = DataCollatorForTokenClassification(
    tokenizer=tokenizer
)

#definiing evaluation
import evaluate
import numpy as np

seqeval = evaluate.load("seqeval")


def compute_metrics(p):
    predictions, labels = p
    predictions = np.argmax(predictions, axis=2)

    true_predictions = [
        [label_list[p] for (p, l) in zip(prediction, label) if l != -100]
        for prediction, label in zip(predictions, labels)
    ]

    true_labels = [
        [label_list[l] for (p, l) in zip(prediction, label) if l != -100]
        for prediction, label in zip(predictions, labels)
    ]

    results = seqeval.compute(
        predictions=true_predictions,
        references=true_labels
    )

    return {
        "precision": results["overall_precision"],
        "recall": results["overall_recall"],
        "f1": results["overall_f1"],
        "accuracy": results["overall_accuracy"],
    }

#defining training settings
from transformers import TrainingArguments

training_args = TrainingArguments(
    output_dir="./xlmr-ner",
    eval_strategy="epoch",
    save_strategy="epoch",
    learning_rate=2e-5,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=8,
    num_train_epochs=3,
    weight_decay=0.01,
    logging_steps=10,
    load_best_model_at_end=True,
    metric_for_best_model="f1",
    greater_is_better=True,
    report_to="none"
)

#creatin trainer object
from transformers import Trainer

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_train,
    eval_dataset=tokenized_test,
    processing_class=tokenizer,
    data_collator=data_collator,
    compute_metrics=compute_metrics,
)
trainer.train()

